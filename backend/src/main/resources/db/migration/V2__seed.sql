-- 시퀀스 보정 (수동 id 삽입 후)
-- Oracle IDENTITY 컬럼에는 setval이 없다. 다음 자동 생성값이 방금 수동으로
-- 넣은 id(=1)와 겹치지 않도록 시작값을 MAX(id)+1로 재설정한다.
DECLARE
    v_next NUMBER;
BEGIN
    SELECT NVL(MAX(id), 0) + 1 INTO v_next FROM users;
    EXECUTE IMMEDIATE 'ALTER TABLE users MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH ' || v_next || ')';
END;
