-- 샘플 사용자 (프론트가 userId=1로 호출)
-- ON CONFLICT (id) DO NOTHING → Oracle은 MERGE로 동일한 "이미 있으면 건너뛰기"를 구현.
MERGE INTO users tgt
USING (SELECT 1 dummy FROM dual) src
ON (tgt.id = 1)
WHEN NOT MATCHED THEN
    INSERT (id, email, department, position)
    VALUES (1, 'byeonghwan@promptune.dev', '마케팅팀', '사원');

-- 선호 설정 (0-2번 온보딩 완료 상태)
MERGE INTO user_preferences tgt
USING (SELECT 1 dummy FROM dual) src
ON (tgt.user_id = 1)
WHEN NOT MATCHED THEN
    INSERT (user_id, speed, detail, preserve)
    VALUES (1, '정확하게', '자세하게', '적극보완');

-- 내부 문서 샘플 (13번 RAG용). embedding은 목업이라 0벡터로 채움.
-- 실제로는 승연이 BGE-M3로 임베딩 생성.
-- array_fill(0, ARRAY[1024])::vector → Oracle은 array_fill이 없어서
-- LISTAGG/CONNECT BY로 '0,0,...,0'(1024개) 문자열을 만들어 TO_VECTOR로 변환한다.
INSERT INTO documents (title, content, embedding) VALUES (
    '휴가 규정 안내',
